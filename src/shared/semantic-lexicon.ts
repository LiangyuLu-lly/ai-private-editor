// 备选项必须按长度降序，否则短的会遮住以它为前缀的长的。这正是
// "联系人 邵桉" 检不出而结构相同的 "收件人 沈砚" 能检出的原因：旧模式把
// `联系(?:一下)?` 排在 `联系人(?:是|为|叫)?` 之前，JS 取最左备选，锚点只吃掉
// "联系"，接着从"人"开始解析姓名必然失败。detector.ts 的 labelAlternation
// 早就这么排了，这里对齐同一做法。
function byDescendingLength(values: readonly string[]): string[] {
  return [...values].sort((left, right) => right.length - left.length || left.localeCompare(right));
}

